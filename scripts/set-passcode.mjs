// Usage: npm run passcode -- "three word phrase"
// Writes the hashed family passcode into src/access/family-passcode.ts.
// The plain passcode is never stored anywhere.
import { writeFileSync } from 'node:fs';
import { webcrypto as crypto } from 'node:crypto';

const SALT = 'colour-stack/family-gate/v1';
const ITERATIONS = 150_000;

const raw = process.argv.slice(2).join(' ');
const passcode = raw.trim().replace(/\s+/g, ' ').toLowerCase();
if (passcode.length < 8) {
  console.error('Please use at least 8 characters, ideally three or more words.');
  process.exit(1);
}

const enc = new TextEncoder();
const key = await crypto.subtle.importKey('raw', enc.encode(passcode), 'PBKDF2', false, ['deriveBits']);
const bits = await crypto.subtle.deriveBits(
  { name: 'PBKDF2', hash: 'SHA-256', salt: enc.encode(SALT), iterations: ITERATIONS },
  key,
  256,
);
const hash = [...new Uint8Array(bits)].map((b) => b.toString(16).padStart(2, '0')).join('');

writeFileSync(
  new URL('../src/access/family-passcode.ts', import.meta.url),
  `// Generated by \`npm run passcode\`. Hash only; the passcode itself is not stored.\nexport const FAMILY_PASSCODE_HASH = '${hash}';\n`,
);
console.log('Family passcode updated. Commit and push to apply it; everyone will need the new passcode.');
